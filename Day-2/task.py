import json
import functools

MODEL = "openai/gpt-oss-20b"

CATALOGUE = {
    "charger": 350,
    "earphones": 250,
    "phone case": 150,
    "usb cable": 100,
    "power bank": 900
}

SYSTEM = f"""
ROLE:
You are a friendly assistant for Mobile Accessories Shop.

FACTS:
Product catalogue and prices in rupees:
{json.dumps(CATALOGUE)}

RULES:
Use only the given product prices.
Do not invent product availability.
If information is unknown, say
I'll check with the owner.

FORMAT:
Give short and friendly answers.
"""

def log_call(func):
    @functools.wraps(func)
    def wrapper(*args, **kwargs):
        result = func(*args, **kwargs)
        print("[LOG]", result)
        return result
    return wrapper

@log_call
def get_price(item: str, qty: int = 1) -> int:
    """Calculate the total price of a product."""
    item = item.lower().strip()

    if item not in CATALOGUE:
        raise ValueError("Product not found")

    if qty <= 0:
        raise ValueError("Quantity must be positive")

    return CATALOGUE[item] * qty

history = [
    {"role": "system", "content": SYSTEM}
]

MAX_TURNS = 8

def chat(user_text):
    history.append({
        "role": "user",
        "content": user_text
    })

    recent = [history[0]] + history[1:][-MAX_TURNS:]

    response = client.chat.completions.create(
        model=MODEL,
        messages=recent,
        temperature=0.3
    )

    reply = response.choices[0].message.content

    history.append({
        "role": "assistant",
        "content": reply
    })

    return reply

print("Price of 2 chargers:", get_price("charger", 2))

